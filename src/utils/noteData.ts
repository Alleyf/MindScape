export function getNoteBySlug(slug: string): Note | undefined {
  return sampleNotes.find(note => note.slug === slug);
}

export function getAllNotes(): Note[] {
  return sampleNotes.sort((a, b) => 
    new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime()
  );
}

export function getRandomNote(excludeSlug?: string): Note {
  const notes = excludeSlug 
    ? sampleNotes.filter(n => n.slug !== excludeSlug)
    : sampleNotes;
  const randomIndex = Math.floor(Math.random() * notes.length);
  return notes[randomIndex];
}

export function getNotesByTag(tag: string): Note[] {
  return sampleNotes.filter(note => note.tags.includes(tag));
}

export function getAllTags(): string[] {
  const tagSet = new Set<string>();
  sampleNotes.forEach(note => {
    note.tags.forEach(tag => tagSet.add(tag));
  });
  return Array.from(tagSet);
}
